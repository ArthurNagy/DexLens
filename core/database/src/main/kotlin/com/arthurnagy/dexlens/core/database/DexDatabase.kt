/** The prebuilt, read-only Pokédex. Generated by `tools/build_database.py` from this class's exported schema. */
@Database(
    entities = [
        SpeciesEntity::class,
        SpeciesNameEntity::class,
        LanguageEntity::class,
        VarietyEntity::class,
        FormEntity::class,
        AbilityEntity::class,
        VarietyAbilityEntity::class,
        EggGroupEntity::class,
        SpeciesEggGroupEntity::class,
        EvolutionEntity::class,
        TypeEfficacyEntity::class,
        GameVersionEntity::class,
        SpeciesNameFtsEntity::class,
    ],
    version = 1,
    exportSchema = true,
)
abstract class DexDatabase : RoomDatabase() {
    abstract fun speciesDao(): SpeciesDao

    abstract fun typeChartDao(): TypeChartDao

    abstract fun gameVersionDao(): GameVersionDao
}
